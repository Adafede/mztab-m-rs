//! Generator and freshness check for `docs/findings.md`.
//!
//! Reads every finding code from [`mztab_m::Code::ALL`] together with its doc
//! comment in `src/diag/code.rs` and verifies that `docs/findings.md` matches the
//! generated table. Run `./mk findings` (or set `BLESS=1`) to rewrite it.

extern crate alloc;

#[cfg(target_arch = "wasm32")]
use wasm_bindgen_test::wasm_bindgen_test as test;

use alloc::collections::BTreeMap;
use core::fmt::Write as _;

use mztab_m::{Code, Layer, Requirement, SPEC_COMMIT, SPEC_VERSION};

const DIAG_RS: &str = include_str!("../src/diag/code.rs");
const COMMITTED: &str = include_str!("../../../docs/findings.md");

/// Extracts the `///` doc comment immediately preceding each `= "MZT-..."`
/// entry in `src/diag/code.rs`.
fn parse_code_docs(source: &str) -> BTreeMap<&str, String> {
    let mut docs = BTreeMap::new();
    let mut current: Vec<&str> = Vec::new();
    let mut in_codes = false;

    for raw in source.lines() {
        let line = raw.trim();
        if line == "codes! {" {
            in_codes = true;
            current.clear();
            continue;
        }
        if !in_codes {
            continue;
        }
        if line == "}" {
            break;
        }
        if let Some(doc) = line.strip_prefix("///") {
            let text = doc.trim();
            if !text.is_empty() {
                current.push(text);
            }
            continue;
        }
        if let Some((_, rest)) = line.split_once("= \"")
            && let Some((id, _)) = rest.split_once('"')
            && id.starts_with("MZT-")
        {
            docs.insert(id, current.join(" "));
            current.clear();
        }
    }

    docs
}

fn escape_cell(text: &str) -> String {
    text.replace('|', "\\|")
}

const fn requirement_label(req: Requirement) -> &'static str {
    match req {
        Requirement::Must => "MUST",
        Requirement::Should => "SHOULD",
        Requirement::May => "MAY",
    }
}

fn severity_cell(code: Code) -> String {
    match code {
        Code::EmptyTable => String::from("`error` / `warning` (MUST / SHOULD)"),
        Code::NullValue => String::from("`error` / `info` (MUST / MAY)"),
        Code::CvRule => String::from("per rule (`error` / `warning` / `info`)"),
        _ => format!(
            "`{}` ({})",
            code.requirement().severity(),
            requirement_label(code.requirement())
        ),
    }
}

const fn layer_heading(layer: Layer) -> (&'static str, &'static str) {
    match layer {
        Layer::Syntax => (
            "Syntax (`MZT-S`)",
            "Reported by the reader for line prefixes, cell grammars, cell counts, encodings, and JSON syntax.",
        ),
        Layer::Structure => (
            "Structure (`MZT-T`)",
            "Reported on the typed model for mandatory fields, profiles, index gaps, cross-references, table columns, and field values.",
        ),
        Layer::Semantic => (
            "Semantic (`MZT-X`)",
            "Reported for controlled-vocabulary declarations, accession format, OBO term checks, and the specification's CV-mapping rules.",
        ),
    }
}

fn generate() -> Result<String, String> {
    let docs = parse_code_docs(DIAG_RS);
    let mut out = String::new();

    out.push_str(
        "<!-- @generated by crates/mztab-m/tests/findings_doc.rs (run ./mk findings or scripts/generate-findings.sh). Do not edit by hand. -->\n\n",
    );
    out.push_str("# Validation findings reference\n\n");
    writeln!(
        out,
        "Every finding emitted by `mztab-m` carries a stable code (`MZT-S*`, `MZT-T*`, or `MZT-X*`), \
         a default severity derived from the rule's RFC 2119 requirement level (`MUST` -> `error`, \
         `SHOULD` -> `warning`, `MAY` -> `info`; a few codes vary by rule or context, noted in the table), \
         a source location, and a link to the specification \
         section at pinned commit [`{short}`](https://github.com/HUPO-PSI/mzTab-M/tree/{SPEC_COMMIT}) \
         (target draft `{SPEC_VERSION}`).",
        short = SPEC_COMMIT.get(..7).unwrap_or(SPEC_COMMIT),
    )
    .map_err(|e| e.to_string())?;
    out.push_str(
        "\nCodes are never reused or renumbered. Severities can be overridden or disabled per code \
         with `--severity CODE=error|warning|info|off` in the CLI or `validate::Config` in Rust.\n\n\
         This page is generated directly from `mztab_m::Code::ALL` (`crates/mztab-m/src/diag/code.rs`). \
         CI fails if it drifts out of sync.\n",
    );

    for layer in [Layer::Syntax, Layer::Structure, Layer::Semantic] {
        let (heading, intro) = layer_heading(layer);
        writeln!(out, "\n## {heading}\n\n{intro}\n").map_err(|e| e.to_string())?;
        out.push_str("| Code | Severity | Meaning | Spec rule | jmzTab-m |\n");
        out.push_str("|---|---|---|---|---|\n");

        for &code in Code::ALL.iter().filter(|c| c.layer() == layer) {
            let id = code.id();
            let meaning = docs
                .get(id)
                .filter(|s| !s.is_empty())
                .ok_or_else(|| format!("missing doc comment in src/diag/code.rs for {id}"))?;
            let severity = severity_cell(code);
            let spec = code.spec_ref();
            let jmztab = if code.jmztab().is_empty() {
                String::from("—")
            } else {
                let mut joined = String::new();
                for (i, n) in code.jmztab().iter().enumerate() {
                    if i > 0 {
                        joined.push_str(", ");
                    }
                    write!(joined, "{n}").map_err(|e| e.to_string())?;
                }
                joined
            };
            writeln!(
                out,
                "| `{id}` | {severity} | {} | [`{}`]({spec}) | {jmztab} |",
                escape_cell(meaning),
                spec.anchor,
            )
            .map_err(|e| e.to_string())?;
        }
    }

    Ok(out)
}

#[test]
fn findings_reference_is_up_to_date() {
    let generated = generate().expect("generate findings reference");
    #[cfg(not(target_arch = "wasm32"))]
    if std::env::var_os("BLESS").is_some() {
        let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../docs/findings.md");
        std::fs::write(path, &generated).expect("write docs/findings.md");
        return;
    }
    assert!(
        generated == COMMITTED,
        "docs/findings.md is stale; run ./mk findings"
    );
}
